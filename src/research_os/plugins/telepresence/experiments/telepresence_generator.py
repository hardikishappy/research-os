    rmse_pred = math.sqrt(sq_err_pred / n)
    rmse_base = math.sqrt(sq_err_base / n)
    red_pct = ((rmse_base - rmse_pred) / rmse_base) * 100.0 if rmse_base > 0 else 0.0
    mean_lat = total_latency_ms / n
    mean_lat_sq = sum((x - mean_lat) ** 2 for x in latencies) / n
    jitter_std = math.sqrt(mean_lat_sq)
    drop_rate = dropped_count / n

    metrics = {
        "tracking_rmse": round(rmse_pred, 4),
        "baseline_tracking_rmse": round(rmse_base, 4),
        "tracking_error_reduction_pct": round(red_pct, 2),
        "packet_drop_rate": round(drop_rate, 4),
        "mean_latency_ms": round(mean_lat, 2),
        "jitter_std_ms": round(jitter_std, 2),
        "total_packets_evaluated": n,
        "status": "COMPLETED",
    }

    return metrics, events


