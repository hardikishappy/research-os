def run_telepresence_simulation(config: dict) -> tuple[dict, list]:
    seed = int(config.get("seed", 42))
    random.seed(seed)

    mean_latency_ms = float(config.get("packet_latency_ms", 120.0))
    jitter_variance_ms = float(config.get("jitter_variance_ms", 35.0))
    loss_rate = float(config.get("packet_loss_rate", 0.08))
    pred_horizon_ms = float(config.get("prediction_horizon_ms", 60.0))
    duration_sec = float(config.get("duration_seconds", 30.0))
    freq_hz = float(config.get("tracking_frequency_hz", 100.0))

    dt = 1.0 / freq_hz
    total_steps = int(duration_sec * freq_hz)

    # Simulated operator trajectory: smooth sinusoidal Lissajous curve with hand tremor
    events = []
    # Delayed queue of packets: (delivery_time_ms, sent_x, sent_y, sent_vx, sent_vy)
    packet_queue = []

    last_received_x = 0.0
    last_received_y = 0.0
    last_received_vx = 0.0
    last_received_vy = 0.0
    last_received_time_ms = 0.0
    last_sent_time_ms = 0.0

    sq_err_pred = 0.0
    sq_err_base = 0.0
    total_latency_ms = 0.0
    latencies = []
    dropped_count = 0

    for step in range(total_steps):
        t_sec = step * dt
        t_ms = t_sec * 1000.0

        # Operator hand position (true ground truth state)
        sx = 0.8 * math.sin(1.2 * t_sec) + 0.02 * random.gauss(0, 0.05)
        sy = 0.6 * math.cos(0.9 * t_sec) + 0.02 * random.gauss(0, 0.05)
        svx = 0.8 * 1.2 * math.cos(1.2 * t_sec)
        svy = -0.6 * 0.9 * math.sin(0.9 * t_sec)

        # Transmit packet across simulated lossy, jittery IP channel
        is_dropped = 1 if random.random() < loss_rate else 0
        jitter = random.gauss(0, jitter_variance_ms)
        effective_latency = max(20.0, mean_latency_ms + jitter)
        delivery_time_ms = t_ms + effective_latency

        if not is_dropped:
            packet_queue.append((delivery_time_ms, sx, sy, svx, svy, effective_latency, t_ms))
        else:
            dropped_count += 1

        # Check delivered packets arriving by current time
        arrived = [p for p in packet_queue if p[0] <= t_ms]
        if arrived:
            # Deliver newest packet
            newest = max(arrived, key=lambda p: p[0])
            last_received_x = newest[1]
            last_received_y = newest[2]
            last_received_vx = newest[3]
            last_received_vy = newest[4]
            last_received_time_ms = newest[0]
            last_sent_time_ms = newest[6]
            packet_queue = [p for p in packet_queue if p[0] > t_ms]

        # 1. Baseline: Uncompensated received position (stale state)
        rx = last_received_x
        ry = last_received_y

        # 2. Proposed: Forward predictive compensation using estimated velocity over jitter horizon
        lag_sec = max(0.0, min(0.3, (t_ms - last_sent_time_ms) / 1000.0))
        px = last_received_x + last_received_vx * lag_sec
        py = last_received_y + last_received_vy * lag_sec

        sq_err_pred += (sx - px) ** 2 + (sy - py) ** 2
        sq_err_base += (sx - rx) ** 2 + (sy - ry) ** 2
        total_latency_ms += effective_latency
        latencies.append(effective_latency)

        events.append({
            "timestamp_ms": round(t_ms, 2),
            "sent_x": round(sx, 4),
            "sent_y": round(sy, 4),
            "received_x": round(rx, 4),
            "received_y": round(ry, 4),
            "predicted_x": round(px, 4),
            "predicted_y": round(py, 4),
            "latency_ms": round(effective_latency, 2),
            "dropped": is_dropped,
        })

