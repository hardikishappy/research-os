"""Staging and Isolation Infrastructure for Just-in-Time Domain Plugins.

Enforces:
- Generated plugins are NEVER staged within src/. All artifacts reside in an external workspace staging directory.
- No immediate execution or import: Staged code remains static files on disk until validated,
  cryptographically approved, and explicitly admitted via DomainRegistry.
"""

from __future__ import annotations

import json
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional, Union

from research_os.domains.declarative import DeclarativeMetricDef, DeclarativePluginSpec
from research_os.models.base import BaseModelAdapter
from research_os.schemas.hypothesis import HypothesisProposal
from research_os.verify.deterministic import compute_file_sha256

DEFAULT_STAGING_BASE_DIR = Path("experiments/staged_plugins")


def validate_staging_path(path: Union[str, Path]) -> None:
    """Ensure that staged plugins are never written inside src/ directory."""
    resolved = Path(path).resolve()
    # Check current workspace src/
    src_path = Path("src").resolve()
    if str(resolved).startswith(str(src_path)):
        raise ValueError(
            f"Staging Isolation Breach: Synthesized plugins must NEVER be written to src/: {resolved}"
        )


def build_default_generator_code(domain_slug: str, target_metric: str, raw_file: str, target_field: str) -> str:
    """Generate safe, static template generator code for generator.py."""
    code_template = f'''"""Autogenerated experiment generator for {domain_slug}."""

from __future__ import annotations
import json
from typing import Any


def generate_code(spec: dict[str, Any]) -> str:
    """Generate simulation code that outputs verified raw telemetry and provenance."""
    spec_id = spec.get("spec_id", "spec-dyn-01")
    return """import json
import os
import random
from pathlib import Path

out_dir = Path("output")
raw_dir = out_dir / "{Path(raw_file).parent.as_posix()}"
raw_dir.mkdir(parents=True, exist_ok=True)

# Generate raw empirical telemetry
num_samples = 40
records = [{{"id": i, "{target_field}": round(random.uniform(0.75, 0.95), 4)}} for i in range(num_samples)]
raw_path = out_dir / "{raw_file}"
with open(raw_path, "w", encoding="utf-8") as f:
    json.dump(records, f, indent=2)

vals = [r["{target_field}"] for r in records]
computed_mean = round(sum(vals) / len(vals), 4)

metrics = {{
    "{target_metric}": computed_mean,
    "sample_count": num_samples,
    "status": "COMPLETED",
}}
with open(out_dir / "metrics.json", "w", encoding="utf-8") as f:
    json.dump(metrics, f, indent=2)

prov = {{
    "metrics": {{
        "{target_metric}": {{
            "reported_value": computed_mean,
            "raw_artifact": {{
                "artifact_id": "art-{target_metric}-raw",
                "relative_path": "{raw_file}",
            }},
            "derivation": {{
                "operation": "mean",
                "target_field": "{target_field}",
            }},
        }}
    }}
}}
with open(out_dir / "provenance.json", "w", encoding="utf-8") as f:
    json.dump(prov, f, indent=2)

with open(out_dir / "summary.txt", "w", encoding="utf-8") as f:
    f.write(f"Protocol completed successfully with mean {target_metric}: {{computed_mean}}\\n")
"""
'''
    return code_template


def synthesize_staged_plugin(
    domain_id: str,
    hypothesis: Optional[HypothesisProposal] = None,
    model_adapter: Optional[BaseModelAdapter] = None,
    staging_base_dir: Optional[Union[str, Path]] = None,
    display_name: Optional[str] = None,
    supported_metrics: Optional[list[str]] = None,
    verification_primitives: Optional[dict[str, DeclarativeMetricDef]] = None,
    generator_code: Optional[str] = None,
    allowed_dependencies: Optional[list[str]] = None,
) -> Path:
    """Synthesize a complete staged domain plugin as static files awaiting approval.

    Enforces:
    - Never stages into src/.
    - Never imports or executes code during synthesis.
    - Writes plugin.json, generator.py, and manifest.json.
    """
    domain_slug = re.sub(r"[^a-zA-Z0-9_]+", "_", domain_id.lower()).strip("_")
    base_dir = Path(staging_base_dir) if staging_base_dir else DEFAULT_STAGING_BASE_DIR
    staged_dir = base_dir / domain_slug

    validate_staging_path(staged_dir)
    staged_dir.mkdir(parents=True, exist_ok=True)

    metrics = list(supported_metrics) if supported_metrics else []
    if not metrics:
        if hypothesis and hypothesis.target_metric:
            metrics.append(hypothesis.target_metric)
        else:
            metrics.append("objective_score")

    primary_metric = metrics[0]
    raw_rel_file = f"raw_data/{primary_metric}_log.json"
    target_field = "score"

    primitives = dict(verification_primitives) if verification_primitives else {}
    if not primitives:
        primitives[primary_metric] = DeclarativeMetricDef(
            metric_id=primary_metric,
            raw_artifact_file=raw_rel_file,
            operation="mean",
            target_field=target_field,
            unit="scalar",
            tolerance=1e-6,
        )

    spec = DeclarativePluginSpec(
        domain_id=domain_slug,
        interface_version="1.0.0",
        display_name=display_name or domain_id.replace("_", " ").title(),
        description=f"Declarative domain plugin for {domain_slug} experimental protocols.",
        supported_metrics=metrics,
        verification_primitives=primitives,
        allowed_dependencies=allowed_dependencies or ["numpy", "pydantic"],
    )

    # 1. Write plugin.json
    spec_path = staged_dir / "plugin.json"
    spec_path.write_text(spec.to_json(), encoding="utf-8")

    # 2. Write generator.py (static code string; NEVER imported or executed)
    gen_code = generator_code or build_default_generator_code(
        domain_slug=domain_slug,
        target_metric=primary_metric,
        raw_file=raw_rel_file,
        target_field=target_field,
    )
    generator_path = staged_dir / "generator.py"
    generator_path.write_text(gen_code, encoding="utf-8")

    # 3. Write manifest.json with content hashes
    spec_sha = compute_file_sha256(spec_path)
    gen_sha = compute_file_sha256(generator_path)

    manifest_data = {
        "domain_id": domain_slug,
        "interface_version": spec.interface_version,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "files": {
            "plugin.json": spec_sha,
            "generator.py": gen_sha,
        },
    }
    manifest_path = staged_dir / "manifest.json"
    manifest_path.write_text(json.dumps(manifest_data, indent=2), encoding="utf-8")

    return staged_dir
