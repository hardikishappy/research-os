class BM25Retriever:
    """Deterministic, genuine BM25 retrieval index across passage collection (rank-bm25)."""

    def __init__(self, documents: list[dict], k1: float = 1.5, b: float = 0.75):
        self.k1 = k1
        self.b = b
        self.docs = documents
        self.N = len(documents)
        self.doc_tokens = [tokenize(d["text"]) for d in documents]
        if HAS_RANK_BM25:
            self._bm25 = BM25Okapi(self.doc_tokens, k1=k1, b=b)
        else:
            self._bm25 = None
            self.doc_lens = [len(toks) for toks in self.doc_tokens]
            self.avgdl = sum(self.doc_lens) / max(1, self.N)

            # Document frequencies
            self.df: dict[str, int] = {}
            for toks in self.doc_tokens:
                for term in set(toks):
                    self.df[term] = self.df.get(term, 0) + 1

            # Inverse Document Frequency (IDF)
            self.idf: dict[str, float] = {}
            for term, freq in self.df.items():
                self.idf[term] = math.log(1.0 + (self.N - freq + 0.5) / (freq + 0.5))

    def retrieve(self, query: str, top_k: int = 3) -> tuple[list[dict], list[float]]:
        """Score and return top_k ranked documents with BM25 scores."""
        q_tokens = tokenize(query)
        if HAS_RANK_BM25 and self._bm25 is not None:
            scores = self._bm25.get_scores(q_tokens)
            ranked_pairs = sorted(enumerate(scores), key=lambda x: x[1], reverse=True)
            top = ranked_pairs[:top_k]
            top_docs = [self.docs[idx] for idx, _ in top]
            top_scores = [float(s) for _, s in top]
            return top_docs, top_scores

        scores = []
        for idx, d_tokens in enumerate(self.doc_tokens):
            score = 0.0
            d_len = self.doc_lens[idx]
            len_norm = 1.0 - self.b + self.b * (d_len / max(1.0, self.avgdl))

            # Term counts in document
            t_counts: dict[str, int] = {}
            for t in d_tokens:
                t_counts[t] = t_counts.get(t, 0) + 1

            for q in q_tokens:
                if q in t_counts:
                    tf = t_counts[q]
                    idf = self.idf.get(q, 0.1)
                    num = tf * (self.k1 + 1.0)
                    denom = tf + self.k1 * len_norm
                    score += idf * (num / denom)
            scores.append((score, idx))

        scores.sort(key=lambda x: x[0], reverse=True)
        top = scores[:top_k]
        top_docs = [self.docs[s[1]] for s in top]
        top_scores = [s[0] for s in top]
        return top_docs, top_scores


def compute_trace_record_hash(sequence_idx, event_type, timestamp_utc, payload, prev_hash):
    """Compute deterministic chained SHA-256 hash for execution trace."""
    canonical_payload = json.dumps(payload, sort_keys=True, separators=(",", ":"))
    content = f"{sequence_idx}|{event_type}|{timestamp_utc}|{canonical_payload}|{prev_hash}"
    return hashlib.sha256(content.encode("utf-8")).hexdigest()


class ExecutionTraceLogger:
    """Cryptographic append-only logger for trace.jsonl."""

    def __init__(self, trace_path: Path):
        self.trace_path = trace_path
        self.trace_path.parent.mkdir(parents=True, exist_ok=True)
        self.seq = 0
        self.prev_hash = "GENESIS"

    def log(self, event_type: str, payload: dict) -> None:
        ts = datetime.now(timezone.utc).isoformat()
        h = compute_trace_record_hash(self.seq, event_type, ts, payload, self.prev_hash)
        record = {
            "sequence_idx": self.seq,
            "event_type": event_type,
            "timestamp_utc": ts,
            "payload": payload,
            "prev_hash": self.prev_hash,
            "trace_hash": h,
        }
        with self.trace_path.open("a", encoding="utf-8") as f:
            f.write(json.dumps(record) + "\\n")
        self.seq += 1
        self.prev_hash = h


def token_overlap_score(prediction: str, gold: str) -> float:
    """Compute token-level recall overlap between prediction and reference answer."""
    pred_tokens = set(tokenize(prediction))
    gold_tokens = set(tokenize(gold))
    if not gold_tokens:
        return 0.0
    overlap = pred_tokens.intersection(gold_tokens)
    return len(overlap) / len(gold_tokens)


class IndependentFactualJudge:
    """Independent evaluation judge evaluating factual faithfulness without asserting gold retrieval."""

    @staticmethod
    def evaluate(prediction_text: str, gold: str, distractors: list[str]) -> tuple[bool, float]:
        """Evaluate if prediction contains factual gold answer or is misled by distractor."""
        pred_toks = tokenize(prediction_text)
        pred_norm = " ".join(pred_toks)
        gold_toks = tokenize(gold)
        gold_norm = " ".join(gold_toks)
        gold_set = set(gold_toks)
        pred_set = set(pred_toks)
        overlap = len(pred_set.intersection(gold_set)) / max(1, len(gold_set))

        has_gold = gold_norm in pred_norm or overlap >= 0.70
        has_distractor = any(" ".join(tokenize(d)) in pred_norm for d in distractors)

        if has_gold and not has_distractor:
            return False, overlap
        elif has_gold and has_distractor:
            return True, overlap
        else:
            return True, overlap


