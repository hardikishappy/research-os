    def install_approved_plugin(
        self,
        plugin_dir_or_draft: Union[Path, PluginDraft],
        gate_token: Optional[HumanGateToken] = None,
        registry: Optional[DomainRegistry] = None,
    ) -> DomainPlugin:
        """Verify human authorization and dynamically register the synthesized plugin."""
        if isinstance(plugin_dir_or_draft, PluginDraft):
            plugin_dir = Path(plugin_dir_or_draft.plugin_dir)
            tok = gate_token or plugin_dir_or_draft.gate_token
        else:
            plugin_dir = Path(plugin_dir_or_draft)
            tok = gate_token

        if tok is None or not tok.is_approved():
            tok_status = tok.status if tok else "MISSING"
            tok_id = tok.gate_id if tok else "None"
            raise PermissionError(
                f"Unauthorized attempt to install domain plugin '{plugin_dir.name}'. "
                f"HumanGateToken '{tok_id}' status is {tok_status} (APPROVED required)."
            )

        reg = registry or default_domain_registry
        plugin_file = plugin_dir / "plugin.py"
        if not plugin_file.exists():
            raise FileNotFoundError(f"Missing plugin.py in {plugin_dir}")

        spec = importlib.util.spec_from_file_location(f"research_os.plugins.{plugin_dir.name}.plugin", plugin_file)
        if not spec or not spec.loader:
            raise ImportError(f"Cannot load module from {plugin_file}")

        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)

        # Find DomainPlugin subclass
        plugin_instance: Optional[DomainPlugin] = None
        for attr_name in dir(module):
            val = getattr(module, attr_name)
            if isinstance(val, type) and issubclass(val, DomainPlugin) and val is not DomainPlugin:
                plugin_instance = val()
                break

        if not plugin_instance:
            raise ValueError(f"No DomainPlugin subclass discovered in {plugin_file}")

        reg.register(plugin_instance)
        return plugin_instance
